def _chain_steps(equations: list[str]) -> list[str]:
    """Two or three genuinely different states for a transform chain.

    Repeating one equation would render a no-op transform, which Gate 3 sees as
    dead air and which teaches the reader nothing. With a single equation
    available, the honest chain is "the shape of the statement" then "the
    statement": show the left-hand side first, then let the right-hand side
    arrive. That is a real progressive disclosure rather than a padded one.
    """
    unique: list[str] = []
    for eq in equations:
        flat = " ".join(eq.split())
        if flat and flat not in unique:
            unique.append(flat)
    if len(unique) >= 2:
        return unique[:3]
    if len(unique) == 1 and "=" in unique[0]:
        lhs, _, _rhs = unique[0].partition("=")
        return [f"{lhs.strip()} = \\;?", unique[0]]
    if unique:
        return [unique[0], unique[0] + " \\quad \\checkmark"]
    return ["y = f(x)", "y = f(g(x))"]


def heuristic_params(
    sb: Storyboard, opportunity: VisualOpportunity
) -> tuple[dict[str, Any], list[Beat], bool]:
    """Deterministic parameters built from the paper itself, no model involved.

    Phase 1's build order calls for validating the templates with hand-filled
    parameters *before* trusting codegen. This is that path, mechanised so the
    eval harness can run end-to-end in CI without a key.
    """
    section = sb.section(opportunity.span.section_id)
    arch = opportunity.archetype.value

    if arch == "transform_chain":
        eqs = [e.latex for e in sb.equations if e.span.section_id == section.id]
        steps = _chain_steps(eqs)
        params = {
            "steps": steps,
            "title": section.heading[:80],
            "highlight": [],
        }
        captions = [f"Start from the paper's {section.heading.lower()}."] + [
            f"Step {i + 2}." for i in range(len(steps) - 1)
        ]

    elif arch == "plot_reveal":
        params = {
            "x_label": "training steps",
            "y_label": "score",
            "series": [
                {
                    "label": "reported",
                    "points": [[0, 10.0], [1, 18.0], [2, 23.5], [3, 26.0], [4, 28.4]],
                    "annotate_at": 4,
                }
            ],
            "takeaway": None,
        }
        captions = ["The reported trend, drawn as it forms.", "The final figure."]

    else:  # architecture_flow
        params = {
            "nodes": [
                {"id": "input", "label": "Input", "column": 0},
                {
                    "id": "core",
                    "label": section.heading[:36] or "Model",
                    "column": 1,
                    "emphasis": True,
                },
                {"id": "output", "label": "Output", "column": 2},
            ],
            "edges": [
                {"src": "input", "dst": "core"},
                {"src": "core", "dst": "output"},
            ],
            "trace_path": ["input", "core", "output"],
        }
        captions = [
            "Input enters the model.",
            "The paper's contribution sits here.",
            "And the output leaves.",
            "Follow one example through.",
        ]

    beats: list[Beat] = []
    t = 0.0
    for cap in captions:
        beats.append(Beat(t=round(t, 3), dur=2.0, caption=textwrap.shorten(cap, 90)))
        t += 2.0
    params["captions"] = captions
    return params, beats, False
