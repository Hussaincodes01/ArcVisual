@dataclass
class GenerateResult:
    scene: Scene
    source: str
    params_obj: Any
    cost_usd: float = 0.0
    #: False when the provider's pricing is unknown to us.
    cost_attributed: bool = True
    provider: str = "heuristic"
    notes: list[str] = field(default_factory=list)


# --------------------------------------------------------------------------- #
# The generated module
# --------------------------------------------------------------------------- #

_MODULE_TEMPLATE = '''\
"""Generated by ArcVisual. Do not edit -- regenerate from the storyboard.

archetype : {archetype}
claim     : {claim}
grounded  : {section_id}[{span_start}:{span_end}]
"""

from {template_module} import Params, build
from arcvisual.templates.base import make_scene

SCENE_ID = {scene_id!r}
ARCHETYPE = {archetype!r}
PARAMS = Params(**{params_json})

# module=__name__ is required: Manim only discovers Scene subclasses whose
# __module__ matches the module it loaded.
{class_name} = make_scene(
    SCENE_ID, ARCHETYPE, build, PARAMS, trace_path={trace_path!r}, module=__name__
)
'''


def scene_class_name(scene_id: str) -> str:
    """The class name Manim's CLI is pointed at."""
    safe = "".join(c if c.isalnum() else "_" for c in scene_id)
    return f"ArcScene_{safe}"


def render_module(
    spec: SceneSpec, params_obj: Any, *, trace_path: str = "trace.json"
) -> str:
    """Emit the module for one scene. Deterministic: same spec, same bytes."""
    template = registry.get(spec.archetype)
    return _MODULE_TEMPLATE.format(
        archetype=spec.archetype.value,
        claim=spec.claim.replace("\n", " ")[:200],
        section_id=spec.span.section_id,
        span_start=spec.span.start,
        span_end=spec.span.end,
        template_module=template.import_path,
        scene_id=spec.id,
        # pprint, not json.dumps: JSON writes `false`/`true`/`null`, which are not
        # Python literals and would land in the module as undefined names. Gate 1
        # catches that, but burning an attempt on our own serialiser is waste.
        # sort_dicts keeps the bytes stable, which keeps the L2 cache warm.
        params_json=pprint.pformat(
            params_obj.model_dump(mode="json"), indent=4, width=84, sort_dicts=True
        ),
        class_name=scene_class_name(spec.id),
        trace_path=trace_path,
    )


