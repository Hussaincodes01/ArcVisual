"""Stage 3 — Generate. Opportunity -> validated parameters -> a thin module.

The central bet of the whole product is here: **the model fills a schema, it does
not write Manim.** Everything about how a scene looks belongs to a tested
template; the model contributes parameters, captions and timing. That shrinks the
failure surface from "any Python" to "does this JSON validate", which is why
first-pass gate rates are worth measuring per archetype.

The generated module is deliberately about eight lines long. Its whole job is to
name a template, hand it validated parameters, and expose a Manim ``Scene``
subclass for the CLI to render. A short generated module is not a stylistic
preference — every line the model does not write is a line that cannot
hallucinate.
"""

